export const FREE_LAYOUT_IDS = [
  "cozy_studio",
  "city_loft",
  "neon_suite",
  "sky_penthouse",
  "garden_lanai",
  "vault_den",
];

export const USER_LAYOUTS = LAYOUTS.filter((l) => FREE_LAYOUT_IDS.includes(l.id));
export const PREMIUM_LAYOUTS = LAYOUTS.filter((l) => l.premium);

export function layoutById(id: string) {
  return LAYOUTS.find((l) => l.id === id) || LAYOUTS[0];
}

export function walkable(layout: Layout, x: number, y: number) {
  if (y < 0 || x < 0 || y >= layout.h || x >= layout.w) return false;
  const c = layout.grid[y][x];
  return c === "." || c === "s" || c === "d" || c === "o" || c === "1" || c === "2" || c === "r" || c === "e";
}

export function tileH(layout: Layout, x: number, y: number) {
  if (y < 0 || x < 0 || y >= layout.h || x >= layout.w) return 0;
  const c = layout.grid[y][x];
  if (c === "1") return 1.2;
  if (c === "2") return 2.35;
  if (c === "r") return 0.58;
  return 0;
}

export function isStair(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "r";
}

export function isDance(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "d";
}

export function isWater(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "~";
}

export function isOutdoor(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "o";
}

export function isDoor(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "e";
}

export function ownsLayout(owned: string[] | undefined, layoutId: string) {
  if (FREE_LAYOUT_IDS.includes(layoutId)) return true;
  return !!owned?.includes(layoutId);
}
