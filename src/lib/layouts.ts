export function layoutById(id: string) {
  return LAYOUTS.find((l) => l.id === id) || LAYOUTS[0];
}

export function walkable(layout: Layout, x: number, y: number) {
  if (y < 0 || x < 0 || y >= layout.h || x >= layout.w) return false;
  const c = layout.grid[y][x];
  return c === "." || c === "s" || c === "d" || c === "o";
}

export function isDance(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "d";
}

export function isWater(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "~";
}

export function isOutdoor(layout: Layout, x: number, y: number) {
  return layout.grid[y]?.[x] === "o";
}
