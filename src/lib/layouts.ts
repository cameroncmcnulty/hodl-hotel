export type Cell = "." | "#" | "s" | "~" | "d" | "o" | "1" | "2" | "r" | "e";

export type Layout = {
  id: string;
  name: string;
  blurb: string;
  w: number;
  h: number;
  spawn: { x: number; y: number };
  grid: Cell[][];
  indoor: boolean;
  premium?: boolean;
  price?: number;
  paper?: string;
  floorA?: string;
  floorB?: string;
};

function parse(
  id: string,
  name: string,
  blurb: string,
  map: string,
  extra: Partial<Layout> = {}
): Layout {
  const rows = map
    .trim()
    .split("\n")
    .map((r) => r.trim().split("") as Cell[]);
  const w = Math.max(...rows.map((r) => r.length));
  for (const r of rows) while (r.length < w) r.push("#");
  const h = rows.length;
  let spawn = { x: Math.floor(w / 2), y: Math.floor(h / 2) };
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (rows[y][x] === "s") {
        spawn = { x, y };
        rows[y][x] = ".";
      }
    }
  }
  if (extra.indoor !== false) placeDoorWestOrNorth(rows, w, h);
  const door = findDoor(rows);
  if (door) spawn = { x: door.x, y: door.y };
  return {
    id,
    name,
    blurb,
    w,
    h,
    spawn,
    grid: rows,
    indoor: extra.indoor !== false,
    premium: extra.premium,
    price: extra.price,
    paper: extra.paper,
    floorA: extra.floorA,
    floorB: extra.floorB,
  };
}

function findDoor(rows: Cell[][]) {
  for (let y = 0; y < rows.length; y++) {
    for (let x = 0; x < (rows[y]?.length || 0); x++) {
      if (rows[y][x] === "e") return { x, y };
    }
  }
  return null;
}

function placeDoorWestOrNorth(rows: Cell[][], w: number, h: number) {
  if (findDoor(rows)) return;
  const west: number[] = [];
  for (let y = 0; y < h; y++) {
    const c = rows[y][0];
    if (c === "." || c === "d" || c === "o" || c === "1" || c === "2" || c === "r") west.push(y);
  }
  if (west.length) {
    rows[west[Math.floor(west.length / 2)]][0] = "e";
    return;
  }
  const north: number[] = [];
  for (let x = 0; x < w; x++) {
    const c = rows[0][x];
    if (c === "." || c === "d" || c === "o" || c === "1" || c === "2" || c === "r") north.push(x);
  }
  if (north.length) rows[0][north[Math.floor(north.length / 2)]] = "e";
}

