export type Cell = "." | "#" | "s" | "~" | "d" | "o";

export type Layout = {
  id: string;
  name: string;
  blurb: string;
  w: number;
  h: number;
  spawn: { x: number; y: number };
  grid: Cell[][];
  indoor: boolean;
};

function parse(id: string, name: string, blurb: string, map: string, indoor = true): Layout {
  const rows = map
    .trim()
    .split("\n")
    .map((r) => r.trim().split("") as Cell[]);
  const h = rows.length;
  const w = rows[0].length;
  let spawn = { x: Math.floor(w / 2), y: Math.floor(h / 2) };
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (rows[y][x] === "s") {
        spawn = { x, y };
        rows[y][x] = ".";
      }
    }
  }
  return { id, name, blurb, w, h, spawn, grid: rows, indoor };
}

